select
    event_id,
    event_type,
    event_date,
    cast(event_date as date) as event_day,
    cast(date_trunc('month', event_date) as date) as event_month,
    customer_id,
    product_id,
    country,
    region,
    channel,
    payment_method,
    currency,
    quantity,
    unit_price_local,
    discount_code,
    (discount_code is not null) as has_discount,
    discount_local,
    round(discount_local * fx_rate_to_usd, 2) as discount_usd,
    tax_local,
    net_revenue_local,
    fx_rate_to_usd,
    net_revenue_usd as revenue_usd_incl_tax,
    round((net_revenue_local - tax_local) * fx_rate_to_usd, 2) as revenue_usd_ex_tax,
    is_refunded,
    refund_datetime,
    refund_reason
from {{ ref('stg_events') }}